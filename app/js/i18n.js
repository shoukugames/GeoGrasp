let lang = 'en';
const listeners = new Set();

export function t(key) { return (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key; }
export function getLang() { return lang; }
export function setLang(l) {
  lang = l === 'ja' ? 'ja' : 'en';
  document.documentElement.lang = lang;
  applyI18n();
  listeners.forEach((fn) => fn(lang));
}
export function onLang(fn) { listeners.add(fn); }
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', el.title); });
}
export function allStrings() { return STR; }
